CREATE TABLE users (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(200) NOT NULL CHECK (btrim(name) <> ''),
    email VARCHAR(255) NOT NULL UNIQUE CHECK (btrim(email) <> '')
);

CREATE TABLE book_editions (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title  VARCHAR(300) NOT NULL CHECK (btrim(title) <> ''),
    author VARCHAR(200) NOT NULL CHECK (btrim(author) <> ''),
    isbn   VARCHAR(32)  NOT NULL UNIQUE CHECK (btrim(isbn) <> '')
);

CREATE TABLE copies (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    edition_id       BIGINT      NOT NULL REFERENCES book_editions (id) ON DELETE CASCADE,
    inventory_number VARCHAR(64) NOT NULL UNIQUE CHECK (btrim(inventory_number) <> ''),
    book_condition   VARCHAR(16) NOT NULL CHECK (book_condition IN ('NEW', 'GOOD', 'WORN', 'DAMAGED'))
);
CREATE INDEX idx_copies_edition ON copies (edition_id);

CREATE TABLE loans (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    copy_id     BIGINT    NOT NULL REFERENCES copies (id) ON DELETE CASCADE,
    user_id     BIGINT    NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    loan_date   TIMESTAMP NOT NULL,
    due_date    TIMESTAMP NOT NULL,
    return_date TIMESTAMP,
    renewals    INT       NOT NULL DEFAULT 0 CHECK (renewals BETWEEN 0 AND 2),
    CHECK (due_date >= loan_date),
    CHECK (return_date IS NULL OR return_date >= loan_date)
);
CREATE INDEX idx_loans_user ON loans (user_id);
-- Один экземпляр не может быть одновременно на руках у двух читателей
CREATE UNIQUE INDEX uq_loans_active_copy ON loans (copy_id) WHERE return_date IS NULL;

CREATE TABLE waiting_requests (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    edition_id       BIGINT      NOT NULL REFERENCES book_editions (id) ON DELETE CASCADE,
    user_id          BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    request_date     TIMESTAMP   NOT NULL,
    status           VARCHAR(16) NOT NULL CHECK (status IN ('WAITING', 'READY', 'FULFILLED', 'CANCELLED')),
    reserved_copy_id BIGINT REFERENCES copies (id) ON DELETE CASCADE,
    -- закреплённый экземпляр есть тогда и только тогда, когда статус READY
    CHECK ((status = 'READY') = (reserved_copy_id IS NOT NULL))
);
CREATE INDEX idx_waiting_edition ON waiting_requests (edition_id);
-- Читатель не может дважды стоять в очереди на одно издание
CREATE UNIQUE INDEX uq_waiting_active ON waiting_requests (edition_id, user_id)
    WHERE status IN ('WAITING', 'READY');
-- Один экземпляр нельзя закрепить за двумя заявками
CREATE UNIQUE INDEX uq_waiting_reserved_copy ON waiting_requests (reserved_copy_id)
    WHERE status = 'READY';

